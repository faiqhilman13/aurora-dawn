#!/usr/bin/env python3
"""Draws every scene and writes them to hooks/scenes.js.

    python3 tools/build.py [--only id,id]

A scene is a file tools/scene_<name>.py that gives ID, NAME, day() and night().
"""

from __future__ import annotations

import argparse
import importlib
import json
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from dither import document  # noqa: E402

# The order they take turns in: a landscape, then a city.
ORDER = ["mountain_lake", "new_york", "desert_mesas", "tokyo", "island_bay", "shanghai"]
# One Svg may hold this many characters.
LIMIT = 131072
ALLOWED = {"svg", "style", "defs", "pattern", "g", "path", "rect"}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--only")
    ap.add_argument("--out", default=str(HERE.parent / "hooks" / "scenes.js"))
    args = ap.parse_args()
    only = set(args.only.split(",")) if args.only else None

    scenes = []
    for name in ORDER:
        try:
            module = importlib.import_module(f"scene_{name}")
        except ModuleNotFoundError:
            print(f"  (no scene_{name}.py yet, left out)")
            continue
        if only and module.ID not in only:
            continue
        svg = document(module.day(), module.night())
        tags = {el.tag.split("}")[1] for el in ET.fromstring(svg).iter()}
        problems = []
        if len(svg) > LIMIT:
            problems.append(f"{len(svg)} characters is over the limit of {LIMIT}")
        if tags - ALLOWED:
            problems.append(f"uses {sorted(tags - ALLOWED)}, which the app's own scenes do not")
        if re.search(r"animation|@keyframes|<script|\son[a-z]+=", svg):
            problems.append("holds something that moves or runs")
        if problems:
            raise SystemExit(f"{module.ID}: " + "; ".join(problems))
        scenes.append({"id": module.ID, "name": module.NAME, "svg": svg})
        print(f"  {module.NAME}: {len(svg)} characters")

    body = ",\n".join("  " + json.dumps(scene) for scene in scenes)
    Path(args.out).write_text(
        "// Generated by tools/build.py from the tools/scene_*.py files. Do not edit by hand: run it again.\n"
        "// Each scene is one SVG holding a picture for light windows and one for dark.\n"
        f"export const SCENES = [\n{body},\n]\n"
    )
    print(f"{args.out}: {len(scenes)} scenes, {Path(args.out).stat().st_size // 1024} KB")


if __name__ == "__main__":
    main()
